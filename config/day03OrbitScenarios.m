function scenarios = day03OrbitScenarios(earthRadiusKm)
%DAY03ORBITSCENARIOS Define six idealized Earth-orbit test cases.
%   Angles are in degrees, semimajor axes are in km, and all states are ECI.

arguments
    earthRadiusKm (1,1) double {mustBePositive, mustBeFinite}
end

scenarios = repmat(struct( ...
    'name', "", 'category', "", 'aKm', 0, 'e', 0, ...
    'iDeg', 0, 'raanDeg', 0, 'argPeriapsisDeg', 0, ...
    'trueAnomalyDeg', 0, 'color', [0 0 0]), 6, 1);

scenarios(1) = makeScenario("LEO 500 km", "Circular LEO", ...
    earthRadiusKm + 500, 0, 28.5, 0, 0, 0, [0.00 0.45 0.74]);
scenarios(2) = makeScenario("GPS-like MEO", "Near-circular MEO", ...
    26560, 0.01, 55, 45, 15, 0, [0.85 0.33 0.10]);
scenarios(3) = makeScenario("Geostationary", "Circular GEO", ...
    42164, 0, 0, 0, 0, 0, [0.47 0.67 0.19]);

% Set the moderate ellipse by a 500 km perigee altitude and e = 0.30.
moderateA = (earthRadiusKm + 500)/(1 - 0.30);
scenarios(4) = makeScenario("Elliptical e=0.30", "Moderate ellipse", ...
    moderateA, 0.30, 40, 80, 30, 0, [0.49 0.18 0.56]);

% Molniya-like geometry: high eccentricity and critical inclination.
scenarios(5) = makeScenario("High-e Molniya-like", "High-e ellipse", ...
    26600, 0.74, 63.4, 120, 270, 0, [0.93 0.69 0.13]);
scenarios(6) = makeScenario("Inclined 98 deg", "Circular inclined", ...
    earthRadiusKm + 1000, 0, 98, 200, 0, 0, [0.30 0.75 0.93]);
end

function scenario = makeScenario(name, category, aKm, e, iDeg, raanDeg, ...
    argPeriapsisDeg, trueAnomalyDeg, color)
scenario = struct('name', name, 'category', category, 'aKm', aKm, ...
    'e', e, 'iDeg', iDeg, 'raanDeg', raanDeg, ...
    'argPeriapsisDeg', argPeriapsisDeg, ...
    'trueAnomalyDeg', trueAnomalyDeg, 'color', color);
end
