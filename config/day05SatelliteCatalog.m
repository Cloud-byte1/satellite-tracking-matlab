%   Catalog IDs are the primary keys. ExpectedNamePattern is used only as a
%   secondary identity check because display names can change.

missionRole = [ ...
    "Crewed space station"; ...
    "Navigation"; ...
    "Navigation"; ...
    "Weather and Earth observation"; ...
    "Earth observation"];
constellation = ["ISS"; "GPS"; "GPS"; "JPSS"; "Landsat"];
