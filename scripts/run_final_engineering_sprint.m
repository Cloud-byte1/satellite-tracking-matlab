function outputs = run_final_engineering_sprint(options)
%RUN_FINAL_ENGINEERING_SPRINT Reproduce the Days 11-14 acceptance package.

arguments
    options.ExportFigures (1,1) logical = true
    options.ShowFigures (1,1) logical = false
    options.BenchmarkDashboard (1,1) logical = true
    options.ReuseCampaign (1,1) logical = true
    options.ApplicationStartupTimeSeconds (1,1) double = NaN
end

scriptDirectory = fileparts(mfilename('fullpath'));
projectRoot = string(fileparts(scriptDirectory));
addpath(projectRoot); setupProject();
addpath(fullfile(projectRoot,'tests')); addpath(fullfile(projectRoot,'apps'));
config = finalSprintConfig(projectRoot);
if ~isfile(config.day07ResultsFile) || ~isfile(config.day09ResultsFile)
    error('runFinalEngineeringSprint:MissingInputs', ...
        'Verified Day 7 and Day 9 result MAT-files are required.');
end
day07 = load(config.day07ResultsFile,'comparison','metrics','catalog', ...
    'referenceVerification','verification','runtimeSeconds');
day09 = load(config.day09ResultsFile,'analysis','verification', ...
    'portfolioMetrics');

savedCampaignFile = fullfile(projectRoot,'results','final_engineering_sprint.mat');
if options.ReuseCampaign && isfile(savedCampaignFile)
    saved = load(savedCampaignFile,'campaign','campaignSummary','representative');
    campaign = saved.campaign;
    campaignSummary = saved.campaignSummary;
    representative = saved.representative;
    campaignElapsedSeconds = campaignSummary.totalRuntimeSeconds;
else
    campaignTimer = tic;
    [campaign,campaignSummary,representative] = ...
        runFinalSimulationCampaign(config);
    campaignElapsedSeconds = toc(campaignTimer);
end
convergence = runSolverConvergenceStudy(day07.comparison,config);
verification = runFinalVerificationSuite(day07,day09, ...
    campaignSummary,convergence,config);

latencyTimer = tic;
for index = 1:config.dashboardLatencySamples
    satelliteIndex = mod(index-1,height(day07.catalog))+1;
    horizons = [1 6 24];
    buildDashboardSnapshot(day07.comparison,day07.catalog, ...
        day09.analysis.summary,satelliteIndex,horizons(mod(index-1,3)+1));
end
predictedPositionUpdateLatencyMilliseconds = ...
    toc(latencyTimer)/config.dashboardLatencySamples*1000;

applicationStartupTimeSeconds = options.ApplicationStartupTimeSeconds;
if options.BenchmarkDashboard
    startupTimer = tic;
    dashboard = SatelliteTrackingDashboard(Visible=false);
    applicationStartupTimeSeconds = toc(startupTimer);
    delete(dashboard.Figure);
end

allSeparations = day07.comparison.positionSeparationKm(:);
gps = day09.analysis.gpsBenchmark;
metricName = ["MaximumPositionSeparationKm"; ...
    "RmsPositionSeparationKm";"MaximumRelativeEnergyDrift"; ...
    "MaximumRelativeAngularMomentumDrift"; ...
    "NumericalPositionConvergenceDifferenceMeters"; ...
    "GpsNetRelativisticClockCorrectionMicrosecondsPerDay"; ...
    "GpsRelativeDifferenceFrom38p5";"SuccessfulSimulationRuns"; ...
    "VerificationTestsPassed";"VerificationTestsFailed"; ...
    "VerificationTestsSkipped";"ApplicationStartupTimeSeconds"; ...
    "PredictedPositionUpdateLatencyMilliseconds"; ...
    "CampaignRuntimeSeconds"];
metricValue = [max(allSeparations);sqrt(mean(allSeparations.^2)); ...
    campaignSummary.maximumRelativeEnergyDrift; ...
    campaignSummary.maximumRelativeAngularMomentumDrift; ...
    convergence.FinalPositionDifferenceMeters(end); ...
    gps.netMicrosecondsPerDay;abs(gps.netMicrosecondsPerDay-38.5)/38.5; ...
    campaignSummary.successfulRuns;verification.passedTests; ...
    verification.failedTests;verification.skippedTests; ...
    applicationStartupTimeSeconds;predictedPositionUpdateLatencyMilliseconds; ...
    campaignElapsedSeconds];
unit = ["km";"km";"relative";"relative";"m"; ...
    "microseconds/day";"relative";"runs";"tests";"tests";"tests"; ...
    "s";"ms";"s"];
performanceMetrics = table(metricName,metricValue,unit, ...
    'VariableNames',{'Metric','Value','Unit'});

resultsDirectory = fullfile(projectRoot,'results');
figuresDirectory = fullfile(projectRoot,'figures');
writetable(campaign,fullfile(resultsDirectory,'final_simulation_campaign.csv'));
writetable(convergence,fullfile(resultsDirectory,'final_solver_convergence.csv'));
writetable(verification.results, ...
    fullfile(resultsDirectory,'final_verification_summary.csv'));
writetable(performanceMetrics, ...
    fullfile(resultsDirectory,'final_performance_metrics.csv'));
save(fullfile(resultsDirectory,'final_engineering_sprint.mat'), ...
    'campaign','campaignSummary','representative','convergence', ...
    'verification','performanceMetrics','config');

figureHandles = gobjects(0);
if options.ExportFigures || options.ShowFigures
    fprintf('Creating final engineering figures...\n');
    figureHandles = plotFinalEngineeringFigures(day07,day09, ...
        convergence,representative);
    if options.ExportFigures
        names = ["final_01_3d_trajectories", ...
            "final_02_sgp4_two_body_separation","final_03_rtn_components", ...
            "final_04_solver_convergence","final_05_energy_conservation", ...
            "final_06_relativistic_clock_drift"];
        for index = 1:numel(figureHandles)
            fprintf('Exporting figure %d of %d: %s\n',index, ...
                numel(figureHandles),names(index));
            exportgraphics(figureHandles(index), ...
                fullfile(figuresDirectory,names(index)+".png"),'Resolution',200);
            savefig(figureHandles(index), ...
                fullfile(figuresDirectory,names(index)+".fig"));
        end
    end
    if ~options.ShowFigures
        close(figureHandles); figureHandles = gobjects(0);
    end
end

fprintf('\nFINAL ENGINEERING SPRINT ACCEPTANCE RUN\n');
fprintf('Simulation runs:             %d/%d passed\n', ...
    campaignSummary.successfulRuns,campaignSummary.totalRuns);
fprintf('Final verification checks:   %d/%d passed\n', ...
    verification.passedTests,verification.totalTests);
fprintf('Maximum SGP4/model separation: %.6f km\n',max(allSeparations));
fprintf('RMS SGP4/model separation:     %.6f km\n', ...
    sqrt(mean(allSeparations.^2)));
fprintf('GPS net correction:            %+.6f microseconds/day\n', ...
    gps.netMicrosecondsPerDay);
fprintf('Dashboard startup:             %.3f s\n', ...
    applicationStartupTimeSeconds);
fprintf('Prediction update latency:     %.3f ms\n\n', ...
    predictedPositionUpdateLatencyMilliseconds);

outputs = struct('campaign',campaign,'campaignSummary',campaignSummary, ...
    'convergence',convergence,'verification',verification, ...
    'performanceMetrics',performanceMetrics,'figures',figureHandles);
end
