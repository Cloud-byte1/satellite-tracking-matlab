function outputs = run_day08_special_relativity(options)
%RUN_DAY08_SPECIAL_RELATIVITY Execute the complete Day 8 workflow.

arguments
    options.ExportFigures (1,1) logical = true
    options.ShowFigures (1,1) logical = true
end

scriptDirectory = fileparts(mfilename('fullpath'));
projectRoot = string(fileparts(scriptDirectory));
addpath(projectRoot); setupProject(); addpath(fullfile(projectRoot,'tests'));
config = day08RelativityConfig(projectRoot);
if ~isfile(config.day07ResultsFile)
    error('runDay08:MissingDay07Results', ...
        'Run Day 7 before Day 8. Missing file: %s',config.day07ResultsFile);
end
day07 = load(config.day07ResultsFile,'comparison','catalog');

profile clear; profile on;
runTimer = tic;
analysis = analyzeDay08ClockScenarios(day07.comparison,day07.catalog,config);
verification = runDay08RelativityTests(analysis,config);
analysisRuntimeSeconds = toc(runTimer);
profile off;
profileInfo = profile('info');
referenceHistory = analysis.histories(1);
clockFunctionBenchmarkSeconds = timeit(@() specialRelativisticClockModel( ...
    referenceHistory.velocityKmPerSec,referenceHistory.elapsedSeconds, ...
    config.speedOfLightKmPerSec, ...
    CoordinateTimeConvention=config.coordinateTimeConvention));

resultsDirectory = fullfile(projectRoot,'results');
figuresDirectory = fullfile(projectRoot,'figures');
writetable(analysis.summary,fullfile(resultsDirectory, ...
    'day08_clock_correction_summary.csv'));
writetable(analysis.timeSeries,fullfile(resultsDirectory, ...
    'day08_clock_correction_timeseries.csv'));
writetable(verification.results,fullfile(resultsDirectory, ...
    'day08_verification.csv'));

gpsDrift = analysis.gpsBenchmark.IntegratedDrift24HoursMicroseconds;
portfolioMetrics = table(analysis.scenarioCount,height(analysis.timeSeries), ...
    gpsDrift,abs(gpsDrift+7.2), ...
    max(abs(analysis.summary.ExactApproxDifferencePicoseconds)), ...
    verification.passedTests,verification.totalTests,4, ...
    abs(analysis.ellipticalVerification.integrationErrorSeconds), ...
    analysisRuntimeSeconds,clockFunctionBenchmarkSeconds*1e3, ...
    'VariableNames',{'ScenarioCount','ClockCorrectionSamples', ...
    'GpsSpecialRelativisticDriftMicrosecondsPerDay', ...
    'GpsDifferenceFromMinus7p2MicrosecondsPerDay', ...
    'MaximumExactApproxDifferencePicoseconds','VerificationChecksPassed', ...
    'VerificationChecksTotal','TechnicalFigureCount', ...
    'EllipticalIntegrationErrorSeconds','AnalysisRuntimeSeconds', ...
    'ClockFunctionBenchmarkMilliseconds'});
writetable(portfolioMetrics,fullfile(resultsDirectory, ...
    'day08_portfolio_metrics.csv'));
save(fullfile(resultsDirectory,'day08_special_relativity.mat'), ...
    'analysis','verification','config','portfolioMetrics','profileInfo');

figureHandles = gobjects(0);
if options.ExportFigures || options.ShowFigures
    figureHandles = plotDay08RelativityFigures(analysis,config);
    if options.ExportFigures
        baseNames = ["day08_drift_vs_altitude", ...
            "day08_accumulated_clock_drift", ...
            "day08_satellite_type_comparison", ...
            "day08_elliptical_clock_rate"];
        for index = 1:numel(figureHandles)
            exportgraphics(figureHandles(index), ...
                fullfile(figuresDirectory,baseNames(index)+".png"), ...
                'Resolution',200);
            savefig(figureHandles(index), ...
                fullfile(figuresDirectory,baseNames(index)+".fig"));
        end
    end
    if ~options.ShowFigures
        close(figureHandles); figureHandles = gobjects(0);
    end
end

fprintf('\nDAY 8: SPECIAL-RELATIVISTIC SATELLITE CLOCK MODEL\n');
fprintf('Scenarios:                    %d (%d real satellites)\n', ...
    analysis.scenarioCount,analysis.realSatelliteCount);
fprintf('Clock-correction samples:     %d\n',height(analysis.timeSeries));
fprintf('GPS theoretical SR drift:     %.6f microseconds/day\n',gpsDrift);
fprintf('Difference from -7.2 us/day:  %.6f microseconds/day\n',abs(gpsDrift+7.2));
fprintf('Verification checks:          %d/%d passed\n', ...
    verification.passedTests,verification.totalTests);
fprintf('Elliptical integration error: %.3e s\n', ...
    abs(analysis.ellipticalVerification.integrationErrorSeconds));
fprintf('Core analysis runtime:        %.3f s\n\n',analysisRuntimeSeconds);
disp(analysis.summary(:,{'ScenarioName','Source','MeanAltitudeKm', ...
    'MeanSpeedKmPerSec','OrbitalPeriodHours', ...
    'IntegratedDrift24HoursMicroseconds'}));

outputs = struct('analysis',analysis,'verification',verification, ...
    'config',config,'portfolioMetrics',portfolioMetrics, ...
    'profileInfo',profileInfo,'figures',figureHandles);
end
