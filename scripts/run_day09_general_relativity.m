function outputs = run_day09_general_relativity(options)
%RUN_DAY09_GENERAL_RELATIVITY Execute the complete Day 9 timing workflow.

arguments
    options.ExportFigures (1,1) logical = true
    options.ShowFigures (1,1) logical = true
end

scriptDirectory = fileparts(mfilename('fullpath'));
projectRoot = string(fileparts(scriptDirectory));
addpath(projectRoot); setupProject(); addpath(fullfile(projectRoot,'tests'));
config = day09RelativityConfig(projectRoot);
if ~isfile(config.day08ResultsFile)
    error('runDay09:MissingDay08Results', ...
        'Run Day 8 before Day 9. Missing file: %s',config.day08ResultsFile);
end
day08 = load(config.day08ResultsFile,'analysis');

runTimer = tic;
analysis = analyzeDay09ClockScenarios(day08.analysis,config);
verification = runDay09RelativityTests(analysis,config);
analysisRuntimeSeconds = toc(runTimer);

resultsDirectory = fullfile(projectRoot,'results');
figuresDirectory = fullfile(projectRoot,'figures');
writetable(analysis.summary,fullfile(resultsDirectory, ...
    'day09_relativistic_timing_summary.csv'));
writetable(analysis.timeSeries,fullfile(resultsDirectory, ...
    'day09_relativistic_timing_timeseries.csv'));
writetable(verification.results,fullfile(resultsDirectory, ...
    'day09_verification.csv'));

gps = analysis.gpsBenchmark;
ellipticalError = abs(analysis.ellipticalVerification.netIntegrationErrorSeconds);
portfolioMetrics = table(analysis.realSatelliteCount,analysis.scenarioCount, ...
    gps.gravitationalMicrosecondsPerDay,gps.kinematicMicrosecondsPerDay, ...
    gps.netMicrosecondsPerDay, ...
    abs(gps.differenceFromStandard38p5MicrosecondsPerDay), ...
    analysis.crossover.altitudeKmAnalytical,verification.passedTests, ...
    verification.totalTests,4,ellipticalError,analysisRuntimeSeconds, ...
    'VariableNames',{'RealSatellitesAnalyzed','TimingScenarioCount', ...
    'GpsGravitationalMicrosecondsPerDay','GpsKinematicMicrosecondsPerDay', ...
    'GpsNetMicrosecondsPerDay','GpsDifferenceFrom38p5MicrosecondsPerDay', ...
    'IdealizedCrossoverAltitudeKm','VerificationChecksPassed', ...
    'VerificationChecksTotal','EngineeringFigureCount', ...
    'EllipticalIntegrationErrorSeconds','AnalysisRuntimeSeconds'});
writetable(portfolioMetrics,fullfile(resultsDirectory, ...
    'day09_portfolio_metrics.csv'));
save(fullfile(resultsDirectory,'day09_general_relativity.mat'), ...
    'analysis','verification','config','portfolioMetrics');

figureHandles = gobjects(0);
if options.ExportFigures || options.ShowFigures
    figureHandles = plotDay09RelativityFigures(analysis,config);
    if options.ExportFigures
        baseNames = ["day09_drift_vs_altitude", ...
            "day09_gps_accumulated_correction", ...
            "day09_orbital_regime_comparison", ...
            "day09_elliptical_clock_behavior"];
        for index = 1:numel(figureHandles)
            exportgraphics(figureHandles(index), ...
                fullfile(figuresDirectory,baseNames(index)+".png"), ...
                'Resolution',200);
            savefig(figureHandles(index), ...
                fullfile(figuresDirectory,baseNames(index)+".fig"));
        end
    end
    if ~options.ShowFigures
        close(figureHandles); figureHandles = gobjects(0);
    end
end

fprintf('\nDAY 9: GRAVITATIONAL AND COMBINED RELATIVISTIC CLOCK MODEL\n');
fprintf('Scenarios:                    %d (%d real satellites)\n', ...
    analysis.scenarioCount,analysis.realSatelliteCount);
fprintf('GPS gravitational drift:     %+.6f microseconds/day\n', ...
    gps.gravitationalMicrosecondsPerDay);
fprintf('GPS kinematic drift:         %+.6f microseconds/day\n', ...
    gps.kinematicMicrosecondsPerDay);
fprintf('GPS combined drift:          %+.6f microseconds/day\n', ...
    gps.netMicrosecondsPerDay);
fprintf('Difference from +38.5:       %.6f microseconds/day\n', ...
    abs(gps.differenceFromStandard38p5MicrosecondsPerDay));
fprintf('Idealized crossover altitude: %.3f km\n', ...
    analysis.crossover.altitudeKmAnalytical);
fprintf('Verification checks:          %d/%d passed\n', ...
    verification.passedTests,verification.totalTests);
fprintf('Elliptical integration error: %.3e s\n',ellipticalError);
fprintf('Core analysis runtime:        %.3f s\n\n',analysisRuntimeSeconds);
disp(analysis.summary(:,{'ScenarioName','MeanAltitudeKm', ...
    'GravitationalMicrosecondsPerDay','KinematicMicrosecondsPerDay', ...
    'NetMicrosecondsPerDay'}));

outputs = struct('analysis',analysis,'verification',verification, ...
    'config',config,'portfolioMetrics',portfolioMetrics, ...
    'figures',figureHandles);
end
