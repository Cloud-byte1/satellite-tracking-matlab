function app = SatelliteTrackingDashboard(options)
%SATELLITETRACKINGDASHBOARD Interactive real-satellite engineering dashboard.
%   The dashboard reads the verified Day 7 SGP4/two-body trajectories and
%   Day 9 relativistic results. It never substitutes display-only orbits.

arguments
    options.Visible (1,1) logical = true
end

appDirectory = fileparts(mfilename('fullpath'));
projectRoot = string(fileparts(appDirectory));
addpath(projectRoot); setupProject(); addpath(fullfile(projectRoot,'scripts'));
day07 = load(fullfile(projectRoot,'results', ...
    'day07_sgp4_two_body_comparison.mat'),'comparison','catalog');
day09 = load(fullfile(projectRoot,'results','day09_general_relativity.mat'), ...
    'analysis');

visibility = 'off';
if options.Visible
    visibility = 'on';
end
figureHandle = uifigure('Name','Satellite Tracking Engineering Dashboard', ...
    'Position',[80 80 1320 780],'Visible',visibility);
root = uigridlayout(figureHandle,[2 2]);
root.RowHeight = {54,'1x'};
root.ColumnWidth = {360,'1x'};

controls = uigridlayout(root,[1 6]);
controls.Layout.Row = 1; controls.Layout.Column = [1 2];
controls.ColumnWidth = {75,230,65,90,150,150};
uilabel(controls,'Text','Satellite');
satelliteDropDown = uidropdown(controls, ...
    'Items',cellstr(string(day07.catalog.SatelliteName)), ...
    'Value',char(string(day07.catalog.SatelliteName(1))));
uilabel(controls,'Text','Horizon');
horizonDropDown = uidropdown(controls,'Items',{'1 h','6 h','24 h'}, ...
    'ItemsData',[1 6 24],'Value',1);
exportButton = uibutton(controls,'Text','Export snapshot');
scenarioButton = uibutton(controls,'Text','Open 3-D globe');

left = uigridlayout(root,[2 1]);
left.Layout.Row = 2; left.Layout.Column = 1;
left.RowHeight = {'1x',190};
summaryArea = uitextarea(left,'Editable','off','FontName','Consolas');
statusArea = uitextarea(left,'Editable','off','FontName','Consolas');
statusArea.Value = { ...
    'Data: verified CelesTrak records propagated with SGP4'; ...
    'Comparison: ode45 two-body minus SGP4'; ...
    'Frame: J2000/FK5 ECI'; ...
    'Timing: satellite minus stationary equatorial surface clock'};

axesHandle = uiaxes(root);
axesHandle.Layout.Row = 2; axesHandle.Layout.Column = 2;
grid(axesHandle,'on'); axis(axesHandle,'equal'); view(axesHandle,3);
xlabel(axesHandle,'J2000 X (km)'); ylabel(axesHandle,'J2000 Y (km)');
zlabel(axesHandle,'J2000 Z (km)');

satelliteDropDown.ValueChangedFcn = @(~,~) updateDashboard();
horizonDropDown.ValueChangedFcn = @(~,~) updateDashboard();
exportButton.ButtonPushedFcn = @(~,~) exportSnapshot();
scenarioButton.ButtonPushedFcn = @(~,~) openScenario();
updateDashboard();

app = struct('Figure',figureHandle,'SatelliteDropDown',satelliteDropDown, ...
    'HorizonDropDown',horizonDropDown,'Axes',axesHandle, ...
    'SummaryArea',summaryArea,'StatusArea',statusArea, ...
    'Comparison',day07.comparison,'Catalog',day07.catalog, ...
    'TimingSummary',day09.analysis.summary);

    function [snapshot,satelliteIndex] = currentSnapshot()
        satelliteIndex = find(string(day07.catalog.SatelliteName)== ...
            string(satelliteDropDown.Value),1);
        snapshot = buildDashboardSnapshot(day07.comparison,day07.catalog, ...
            day09.analysis.summary,satelliteIndex,horizonDropDown.Value);
    end

    function updateDashboard()
        [snapshot,satelliteIndex] = currentSnapshot();
        horizonIndex = find(day07.comparison.elapsedSeconds<= ...
            snapshot.HorizonHours*3600);
        rSgp4 = day07.comparison.positionSgp4J2000Km( ...
            horizonIndex,:,satelliteIndex);
        rTwoBody = day07.comparison.positionTwoBodyJ2000Km( ...
            horizonIndex,:,satelliteIndex);
        cla(axesHandle);
        [xEarth,yEarth,zEarth] = sphere(40);
        earthRadius = day07.comparison.config.earthRadiusKm;
        surf(axesHandle,xEarth*earthRadius,yEarth*earthRadius, ...
            zEarth*earthRadius,'FaceColor',[0.12 0.34 0.62], ...
            'EdgeColor','none','FaceAlpha',0.72);
        hold(axesHandle,'on');
        plot3(axesHandle,rSgp4(:,1),rSgp4(:,2),rSgp4(:,3), ...
            'LineWidth',2,'DisplayName','SGP4');
        plot3(axesHandle,rTwoBody(:,1),rTwoBody(:,2),rTwoBody(:,3), ...
            '--','LineWidth',1.5,'DisplayName','ode45 two-body');
        hold(axesHandle,'off'); legend(axesHandle,'Location','best');
        title(axesHandle,sprintf('%s — %.0f-hour prediction', ...
            snapshot.SatelliteName,snapshot.HorizonHours));
        summaryArea.Value = composeSummary(snapshot);
        drawnow limitrate;
    end

    function exportSnapshot()
        snapshot = currentSnapshot();
        output = struct2table(snapshot,'AsArray',true);
        outputFile = fullfile(projectRoot,'results','dashboard_snapshot.csv');
        writetable(output,outputFile);
        statusArea.Value = [statusArea.Value; ...
            {sprintf('Exported %s',outputFile)}];
    end

    function openScenario()
        statusArea.Value = [statusArea.Value; ...
            {'Opening cached five-satellite satelliteScenario...'}];
        drawnow;
        run_day05_satellite_scenario(ForceRefresh=false,ShowViewer=true, ...
            ShowGroundTracks=true,ShowObservationPanel=true);
    end
end

function lines = composeSummary(snapshot)
position = snapshot.Sgp4PositionJ2000Km;
velocity = snapshot.Sgp4VelocityJ2000KmPerSec;
rtn = snapshot.RtnSeparationKm;
lines = { ...
    sprintf('%s  |  NORAD %d  |  %s',snapshot.SatelliteName, ...
        snapshot.NORADCatalogID,snapshot.Regime); ...
    sprintf('UTC: %s',string(snapshot.PredictionTimeUtc, ...
        "yyyy-MM-dd HH:mm:ss 'UTC'")); ...
    sprintf('Horizon: %.0f h',snapshot.HorizonHours); ...
    ''; ...
    'SGP4 J2000 state'; ...
    sprintf('r = [%10.3f %10.3f %10.3f] km',position); ...
    sprintf('v = [%10.6f %10.6f %10.6f] km/s',velocity); ...
    ''; ...
    sprintf('|two-body - SGP4| = %.6f km',snapshot.PositionSeparationKm); ...
    sprintf('RTN = [%+.6f %+.6f %+.6f] km',rtn); ...
    ''; ...
    'Relativistic clock drift'; ...
    sprintf('gravity:   %+.6f microseconds/day', ...
        snapshot.GravitationalMicrosecondsPerDay); ...
    sprintf('kinematic: %+.6f microseconds/day', ...
        snapshot.KinematicMicrosecondsPerDay); ...
    sprintf('net:       %+.6f microseconds/day', ...
        snapshot.NetMicrosecondsPerDay)};
end
