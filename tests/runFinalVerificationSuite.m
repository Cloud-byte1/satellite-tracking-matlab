function report = runFinalVerificationSuite(day07,day09, ...
    campaignSummary,convergence,config)
%RUNFINALVERIFICATIONSUITE Consolidated Days 11-14 acceptance checks.

mu = config.muEarthKm3PerSec2;
radius = config.earthRadiusKm+20200;
analyticalSpeed = sqrt(mu/radius);
analyticalPeriod = 2*pi*sqrt(radius^3/mu);
[r0,v0] = orbitalElementsToState(struct('aKm',radius,'e',0, ...
    'iDeg',55,'raanDeg',0,'argPeriapsisDeg',0,'trueAnomalyDeg',0),mu);
circular = propagateTwoBody([r0;v0],linspace(0,analyticalPeriod,361).', ...
    mu,RelativeTolerance=1e-12,AbsoluteTolerance=1e-13,MaximumStep=30);
circularDiagnostics = orbitDiagnostics(circular);
speedRelativeError = abs(norm(v0)-analyticalSpeed)/analyticalSpeed;
periodClosureErrorKm = norm(circular.position(end,:)-circular.position(1,:));

initialPositionMismatch = max(vecnorm(reshape( ...
    day07.comparison.positionDifferenceJ2000Km(1,:,:),3,[]).',2,2));
frameOrthogonality = max([day07.comparison.frameMetadata. ...
    maximumRotationOrthogonalityError]);
rtnClosure = max(day07.comparison.rtnReconstructionErrorKm,[],'all');
gps = day09.analysis.gpsBenchmark;
snapshot = buildDashboardSnapshot(day07.comparison,day07.catalog, ...
    day09.analysis.summary,1,24);
snapshotFinite = all(isfinite([snapshot.Sgp4PositionJ2000Km ...
    snapshot.Sgp4VelocityJ2000KmPerSec snapshot.PositionSeparationKm ...
    snapshot.RtnSeparationKm snapshot.NetMicrosecondsPerDay]));

testName = [ ...
    "Circular-orbit analytical velocity"; ...
    "Circular-orbit analytical period closure"; ...
    "Specific orbital energy conservation"; ...
    "Angular momentum conservation"; ...
    "Elliptical perigee agreement"; ...
    "Elliptical apogee agreement"; ...
    "Numerical convergence against tight solution"; ...
    "SGP4 and two-body initial-state consistency"; ...
    "Published Vallado SGP4 reference cases"; ...
    "TEME-to-J2000 rotation consistency"; ...
    "RTN reconstruction consistency"; ...
    "Special-relativistic GPS correction"; ...
    "Gravitational GPS correction"; ...
    "Combined GPS clock correction"; ...
    "CelesTrak catalog parsing and uniqueness"; ...
    "Dashboard propagated-data integrity"; ...
    "Automated simulation campaign success"];
measuredValue = [speedRelativeError;periodClosureErrorKm; ...
    campaignSummary.maximumRelativeEnergyDrift; ...
    campaignSummary.maximumRelativeAngularMomentumDrift; ...
    campaignSummary.maximumPerigeeErrorKm; ...
    campaignSummary.maximumApogeeErrorKm; ...
    convergence.FinalPositionDifferenceMeters(end); ...
    initialPositionMismatch;double(day07.referenceVerification.allPassed); ...
    frameOrthogonality;rtnClosure; ...
    abs(gps.kinematicMicrosecondsPerDay+7.2); ...
    abs(gps.gravitationalMicrosecondsPerDay-45.7); ...
    abs(gps.netMicrosecondsPerDay-38.5); ...
    double(height(day07.catalog)>=5 && ...
        numel(unique(day07.catalog.NORADCatalogID))==height(day07.catalog)); ...
    double(snapshotFinite && snapshot.SatelliteName== ...
        string(day07.catalog.SatelliteName(1))); ...
    campaignSummary.successfulRuns];
comparison = ["<=";"<=";"<=";"<=";"<=";"<=";"<=";"<="; ...
    "==";"<=";"<=";"<=";"<=";"<=";"==";"==";">="];
criterion = [1e-13;0.01;config.maximumRelativeEnergyDrift; ...
    config.maximumRelativeAngularMomentumDrift; ...
    config.maximumApsisErrorKm;config.maximumApsisErrorKm;10;1e-9;1; ...
    1e-10;1e-9;0.15;0.2;0.25;1;1;100];
passed = [measuredValue(1)<=criterion(1); ...
    measuredValue(2)<=criterion(2);measuredValue(3)<=criterion(3); ...
    measuredValue(4)<=criterion(4);measuredValue(5)<=criterion(5); ...
    measuredValue(6)<=criterion(6);measuredValue(7)<=criterion(7); ...
    measuredValue(8)<=criterion(8);measuredValue(9)==criterion(9); ...
    measuredValue(10)<=criterion(10);measuredValue(11)<=criterion(11); ...
    measuredValue(12)<=criterion(12);measuredValue(13)<=criterion(13); ...
    measuredValue(14)<=criterion(14);measuredValue(15)==criterion(15); ...
    measuredValue(16)==criterion(16);measuredValue(17)>=criterion(17)];
unit = ["relative";"km";"relative";"relative";"km";"km";"m"; ...
    "km";"logical";"Frobenius norm";"km";"microseconds/day"; ...
    "microseconds/day";"microseconds/day";"logical";"logical";"runs"];
results = table(testName,measuredValue,comparison,criterion,unit,passed, ...
    'VariableNames',{'Test','MeasuredValue','Comparison','Criterion', ...
    'Unit','Passed'});
report = struct('results',results,'passedTests',sum(passed), ...
    'failedTests',sum(~passed),'skippedTests',0,'totalTests',height(results), ...
    'allPassed',all(passed),'circularDiagnostics',circularDiagnostics);
if ~report.allPassed
    error('runFinalVerificationSuite:VerificationFailure', ...
        'Failed checks: %s.',strjoin(cellstr(testName(~passed)),', '));
end
end
