function report = runDay07ComparisonTests(comparison,metrics,catalog)
%RUNDAY07COMPARISONTESTS Verify numerical and frame consistency.

satelliteCount = height(catalog);
expectedCases = satelliteCount*3;
initialPositionMismatch = max(vecnorm( ...
    squeeze(comparison.positionDifferenceJ2000Km(1,:,:)).',2,2));
initialVelocityMismatch = max(vecnorm( ...
    squeeze(comparison.velocityDifferenceJ2000KmPerSec(1,:,:)).',2,2));
orthogonalityError = 0;
for satellite = 1:satelliteCount
    for index = [1 numel(comparison.timeUtc)]
        rotation = squeeze(comparison.rtnBasis(index,:,:,satellite));
        orthogonalityError = max(orthogonalityError, ...
            norm(rotation.'*rotation-eye(3),'fro'));
    end
end
separationCheck = max(abs(comparison.positionSeparationKm- ...
    squeeze(vecnorm(comparison.positionDifferenceJ2000Km,2,2))),[],'all');
repeat = propagateTwoBody([comparison.positionSgp4J2000Km(1,:,1) ...
    comparison.velocitySgp4J2000KmPerSec(1,:,1)].', ...
    comparison.elapsedSeconds,comparison.twoBodyMuKm3PerSec2, ...
    RelativeTolerance=comparison.config.relativeTolerance, ...
    AbsoluteTolerance=comparison.config.absoluteTolerance, ...
    MaximumStep=comparison.config.maximumStepSeconds);
repeatError = max(abs(repeat.state-[comparison.positionTwoBodyJ2000Km(:,:,1) ...
    comparison.velocityTwoBodyJ2000KmPerSec(:,:,1)]),[],'all');

testName = ["At least five satellites";"Three horizons per satellite"; ...
    "All satellite-horizon cases present";"Initial positions match"; ...
    "Initial velocities match";"UTC timestamps strictly increase"; ...
    "SGP4 error codes all zero";"All propagated states finite"; ...
    "Frame rotations orthogonal";"RTN bases orthogonal"; ...
    "RTN reconstruction closes";"Separation magnitudes correct"; ...
    "Comparison is reproducible";"All three orbital regimes represented"; ...
    "All metrics nonnegative where required"];
measuredValue = [satelliteCount;numel(unique(metrics.HorizonHours)); ...
    height(metrics);initialPositionMismatch;initialVelocityMismatch; ...
    double(all(diff(comparison.timeUtc)>seconds(0))); ...
    max(comparison.sgp4ErrorCode,[],'all'); ...
    double(all(isfinite(comparison.positionSgp4J2000Km),'all') && ...
    all(isfinite(comparison.positionTwoBodyJ2000Km),'all')); ...
    max([comparison.frameMetadata.maximumRotationOrthogonalityError]); ...
    orthogonalityError;max(comparison.rtnReconstructionErrorKm,[],'all'); ...
    separationCheck;repeatError;numel(unique(catalog.Regime)); ...
    double(all(metrics.MaximumPositionSeparationKm>=0) && ...
    all(metrics.RmsPositionSeparationKm>=0) && ...
    all(metrics.FinalVelocityDifferenceKmPerSec>=0))];
comparisonOperator = [">=";"==";"==";"<=";"<=";"==";"=="; ...
    "==";"<=";"<=";"<=";"<=";"<=";">=";"=="];
criterion = [5;3;expectedCases;1e-9;1e-12;1;0;1;1e-10;1e-12; ...
    1e-9;1e-12;1e-10;3;1];
passed = [measuredValue(1)>=criterion(1);measuredValue(2)==criterion(2); ...
    measuredValue(3)==criterion(3);measuredValue(4)<=criterion(4); ...
    measuredValue(5)<=criterion(5);measuredValue(6)==criterion(6); ...
    measuredValue(7)==criterion(7);measuredValue(8)==criterion(8); ...
    measuredValue(9)<=criterion(9);measuredValue(10)<=criterion(10); ...
    measuredValue(11)<=criterion(11);measuredValue(12)<=criterion(12); ...
    measuredValue(13)<=criterion(13);measuredValue(14)>=criterion(14); ...
    measuredValue(15)==criterion(15)];
unit = ["satellites";"horizons";"cases";"km";"km/s";"logical"; ...
    "code";"logical";"Frobenius norm";"Frobenius norm";"km"; ...
    "km";"state units";"regimes";"logical"];
results = table(testName,measuredValue,comparisonOperator,criterion,unit,passed, ...
    'VariableNames',{'Test','MeasuredValue','Comparison','Criterion','Unit','Passed'});
report = struct('results',results,'passedTests',sum(passed), ...
    'totalTests',height(results),'allPassed',all(passed));
if ~report.allPassed
    error('runDay07ComparisonTests:VerificationFailure','Failed checks: %s.', ...
        strjoin(cellstr(testName(~passed)),', '));
end
end
