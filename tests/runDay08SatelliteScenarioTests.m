function report = runDay08SatelliteScenarioTests(scenario,satellites,analysis)
%RUNDAY08SATELLITESCENARIOTESTS Verify the Day 8 native viewer inputs.

count = numel(satellites);
expectedCount = analysis.scenarioCount;
positionErrorMeters = zeros(count,1);
velocityErrorMetersPerSecond = zeros(count,1);
propagators = strings(count,1);
for index = 1:count
    [position,velocity] = states(satellites(index),scenario.StartTime, ...
        'CoordinateFrame','inertial');
    expectedPosition = analysis.histories(index).positionKm(1,:).'*1000;
    expectedVelocity = analysis.histories(index).velocityKmPerSec(1,:).'*1000;
    positionErrorMeters(index) = norm(position(:)-expectedPosition);
    velocityErrorMetersPerSecond(index) = norm(velocity(:)-expectedVelocity);
    propagators(index) = string(satellites(index).OrbitPropagator);
end

testName = [ ...
    "All nine Day 8 scenarios loaded"; ...
    "Six real Day 8 satellites retained"; ...
    "Three theoretical Day 8 orbits retained"; ...
    "All viewer trajectories use saved ephemerides"; ...
    "Initial positions match Day 8 histories"; ...
    "Initial velocities match Day 8 histories"; ...
    "Viewer spans the complete 24-hour analysis"; ...
    "Clock drift values are finite"];
measuredValue = [count;analysis.realSatelliteCount; ...
    count-analysis.realSatelliteCount;sum(propagators=="ephemeris"); ...
    max(positionErrorMeters);max(velocityErrorMetersPerSecond); ...
    seconds(scenario.StopTime-scenario.StartTime); ...
    double(all(isfinite(analysis.summary.IntegratedDrift24HoursMicroseconds)))];
criterion = [expectedCount;6;3;expectedCount;1e-6;1e-9;86400;1];
comparison = ["==";"==";"==";"==";"<=";"<=";"==";"=="];
passed = [measuredValue(1:4)==criterion(1:4); ...
    measuredValue(5)<=criterion(5);measuredValue(6)<=criterion(6); ...
    measuredValue(7)==criterion(7);measuredValue(8)==criterion(8)];
unit = ["scenarios";"satellites";"orbits";"satellites"; ...
    "m";"m/s";"s";"logical"];
results = table(testName,measuredValue,comparison,criterion,unit,passed, ...
    'VariableNames',{'Test','MeasuredValue','Comparison','Criterion','Unit','Passed'});
report = struct('results',results,'passedTests',sum(passed), ...
    'totalTests',height(results),'allPassed',all(passed));
if ~report.allPassed
    failed = strjoin(cellstr(testName(~passed)),', ');
    error('runDay08SatelliteScenarioTests:VerificationFailure', ...
        'Day 8 satelliteScenario verification failed: %s',failed);
end
end
