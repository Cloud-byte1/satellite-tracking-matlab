function report = runSatelliteObservationTests(simulation,earthRadiusKm)
%RUNSATELLITEOBSERVATIONTESTS Verify timeline state inspection calculations.

satelliteIndex = min(2,numel(simulation.catalogIds));
frameIndex = min(3,numel(simulation.timeUtc));
observation = observeSatelliteState( ...
    simulation,satelliteIndex,frameIndex,earthRadiusKm);
expectedPosition = reshape( ...
    simulation.positionTemeKm(frameIndex,:,satelliteIndex),1,3);
expectedVelocity = reshape( ...
    simulation.velocityTemeKmPerSec(frameIndex,:,satelliteIndex),1,3);

testName = [ ...
    "Selected satellite is preserved"; ...
    "Selected timeline frame is preserved"; ...
    "UTC sample matches propagated history"; ...
    "TEME position matches propagated history"; ...
    "TEME velocity matches propagated history"; ...
    "Altitude uses configured Earth radius"; ...
    "Speed is the velocity-vector norm"; ...
    "All displayed values are finite"];
measuredValue = [ ...
    double(observation.satelliteIndex==satelliteIndex); ...
    double(observation.frameIndex==frameIndex); ...
    abs(seconds(observation.timeUtc-simulation.timeUtc(frameIndex))); ...
    norm(observation.positionKm-expectedPosition); ...
    norm(observation.velocityKmPerSec-expectedVelocity); ...
    abs(observation.altitudeKm-(norm(expectedPosition)-earthRadiusKm)); ...
    abs(observation.speedKmPerSec-norm(expectedVelocity)); ...
    double(all(isfinite([observation.positionKm,observation.velocityKmPerSec, ...
        observation.altitudeKm,observation.speedKmPerSec])))];
criterion = [1;1;0;0;0;1e-12;1e-12;1];
comparison = ["==";"==";"==";"==";"==";"<=";"<=";"=="];
passed = [measuredValue(1:5)==criterion(1:5); ...
    measuredValue(6:7)<=criterion(6:7);measuredValue(8)==criterion(8)];
unit = ["logical";"logical";"s";"km";"km/s";"km";"km/s";"logical"];
results = table(testName,measuredValue,comparison,criterion,unit,passed, ...
    'VariableNames',{'Test','MeasuredValue','Comparison','Criterion','Unit','Passed'});
report = struct('results',results,'passedTests',sum(passed), ...
    'totalTests',height(results),'allPassed',all(passed));
if ~report.allPassed
    failed = strjoin(cellstr(testName(~passed)),', ');
    error('runSatelliteObservationTests:VerificationFailure', ...
        'Satellite observation verification failed: %s',failed);
end
end
