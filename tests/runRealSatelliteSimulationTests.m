function report = runRealSatelliteSimulationTests(simulation, earthRadiusKm)
%RUNREALSATELLITESIMULATIONTESTS Verify five-satellite SGP4 output.

radii = zeros(size(simulation.sgp4ErrorCode));
speeds = zeros(size(simulation.sgp4ErrorCode));
for index = 1:numel(simulation.catalogIds)
    radii(:,index) = vecnorm(simulation.positionTemeKm(:,:,index),2,2);
    speeds(:,index) = vecnorm(simulation.velocityTemeKmPerSec(:,:,index),2,2);
end
expectedSamples = round(simulation.durationHours*3600/simulation.stepSeconds)+1;
testName = [ ...
    "Five satellites propagated"; ...
    "All requested time samples returned"; ...
    "All SGP4 calls report success"; ...
    "All TEME states are finite"; ...
    "All satellite radii remain above Earth"; ...
    "All orbital speeds are physically plausible"; ...
    "Catalog IDs remain unique"; ...
    "Common UTC timeline is monotonic"];
measuredValue = [numel(simulation.catalogIds);numel(simulation.timeUtc); ...
    max(simulation.sgp4ErrorCode,[],'all'); ...
    double(all(isfinite(simulation.positionTemeKm),'all') && ...
        all(isfinite(simulation.velocityTemeKmPerSec),'all')); ...
    min(radii,[],'all')-earthRadiusKm;max(speeds,[],'all'); ...
    numel(unique(simulation.catalogIds)); ...
    double(all(diff(simulation.timeUtc)>seconds(0)))];
criterion = [5;expectedSamples;0;1;100;15;5;1];
comparison = ["==";"==";"==";"==";">";"<";"==";"=="];
passed = [measuredValue(1)==criterion(1);measuredValue(2)==criterion(2); ...
    measuredValue(3)==criterion(3);measuredValue(4)==criterion(4); ...
    measuredValue(5)>criterion(5);measuredValue(6)<criterion(6); ...
    measuredValue(7)==criterion(7);measuredValue(8)==criterion(8)];
unit = ["satellites";"samples";"code";"logical";"km";"km/s";"IDs";"logical"];
results = table(testName,measuredValue,comparison,criterion,unit,passed, ...
    'VariableNames',{'Test','MeasuredValue','Comparison','Criterion','Unit','Passed'});
report = struct('results',results,'passedTests',sum(passed), ...
    'totalTests',height(results),'allPassed',all(passed));
if ~report.allPassed
    failedNames = strjoin(cellstr(testName(~passed)),', ');
    error('runRealSatelliteSimulationTests:VerificationFailure', ...
        'Real-satellite simulation tests failed: %s',failedNames);
end
end
