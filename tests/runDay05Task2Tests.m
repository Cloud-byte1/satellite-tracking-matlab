function report = runDay05Task2Tests()
%RUNDAY05TASK2TESTS Deterministically test retrieval, validation, and caching.

temporaryDirectory = string(tempname);
mkdir(temporaryDirectory);
cleanup = onCleanup(@() removeTemporaryDirectory(temporaryDirectory));
fixtureTime = datetime(2026,10,18,18,0,0,'TimeZone','UTC');
validCsv = validFixture();

networkResult = fetchCelesTrakGp("CATNR", "25544", ...
    CacheDirectory=temporaryDirectory, ForceRefresh=true, ...
    FetchFunction=@(~,~) validCsv, NowUtc=fixtureTime);
cacheResult = fetchCelesTrakGp("CATNR", "25544", ...
    CacheDirectory=temporaryDirectory, ...
    FetchFunction=@unexpectedNetworkCall, NowUtc=fixtureTime + minutes(30));
warningState = warning('off', 'fetchCelesTrakGp:UsingStaleCache');
warningCleanup = onCleanup(@() warning(warningState));
staleFallback = fetchCelesTrakGp("CATNR", "25544", ...
    CacheDirectory=temporaryDirectory, ForceRefresh=true, ...
    FetchFunction=@simulatedNetworkFailure, ...
    NowUtc=fixtureTime + hours(3));

malformedRejected = false;
try
    fetchCelesTrakGp("CATNR", "25544", ...
        CacheDirectory=string(tempname), ForceRefresh=true, ...
        AllowStaleOnFailure=false, ...
        FetchFunction=@(~,~) "OBJECT_NAME,NORAD_CAT_ID" + newline + "ISS,25544", ...
        NowUtc=fixtureTime);
catch exception
    malformedRejected = contains(exception.message, 'missing required fields', ...
        'IgnoreCase', true);
end

testName = [ ...
    "Valid CSV is retrieved and typed"; ...
    "Successful response is saved with provenance"; ...
    "Fresh cache prevents a network request"; ...
    "Network failure falls back to valid stale cache"; ...
    "Malformed response is rejected"; ...
    "Element epoch and retrieval time remain separate"];
passed = [ ...
    height(networkResult.Records) == 1 && ...
        isdatetime(networkResult.Records.EPOCH); ...
    networkResult.Metadata.Source == "network" && ...
        isfile(fullfile(temporaryDirectory, networkResult.Metadata.RawFileName)); ...
    cacheResult.Metadata.Source == "cache"; ...
    staleFallback.Metadata.Source == "stale-cache" && ...
        strlength(staleFallback.Metadata.NetworkError) > 0; ...
    malformedRejected; ...
    networkResult.Records.EPOCH(1) ~= ...
        networkResult.Metadata.RetrievedAtUtc];

results = table(testName, passed, ...
    'VariableNames', {'Test','Passed'});
report = struct('results', results, 'totalTests', height(results), ...
    'passedTests', sum(passed), 'allPassed', all(passed));
if ~report.allPassed
    failedNames = strjoin(cellstr(testName(~passed)), ', ');
    error('runDay05Task2Tests:VerificationFailure', ...
        'Day 5 Task 2 tests failed: %s', failedNames);
end
end

function csv = validFixture()
csv = "OBJECT_NAME,OBJECT_ID,EPOCH,MEAN_MOTION,ECCENTRICITY," + ...
    "INCLINATION,RA_OF_ASC_NODE,ARG_OF_PERICENTER,MEAN_ANOMALY," + ...
    "EPHEMERIS_TYPE,CLASSIFICATION_TYPE,NORAD_CAT_ID,ELEMENT_SET_NO," + ...
    "REV_AT_EPOCH,BSTAR,MEAN_MOTION_DOT,MEAN_MOTION_DDOT" + newline + ...
    "ISS (ZARYA),1998-067A,2026-10-18T12:00:00.000000," + ...
    "15.49,0.00042,51.64,30.0,40.0,50.0,0,U,25544,999,12345," + ...
    "0.0001,0.00001,0.0";
end

function unexpectedNetworkCall(varargin)
error('runDay05Task2Tests:UnexpectedNetworkCall', ...
    'Fresh cache should have prevented this request.');
end

function simulatedNetworkFailure(varargin)
error('runDay05Task2Tests:SimulatedNetworkFailure', ...
    'Simulated connection failure.');
end

function removeTemporaryDirectory(directory)
if isfolder(directory)
    rmdir(directory, 's');
end
end
