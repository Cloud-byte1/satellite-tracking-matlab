function report = runDay09RelativityTests(analysis,config)
%RUNDAY09RELATIVITYTESTS Verify Day 9 physics and numerical behavior.

time = [0;config.secondsPerDay];
surface = gravitationalTimeDilationModel( ...
    [config.earthRadiusKm;config.earthRadiusKm],time, ...
    config.muEarthKm3PerSec2,config.earthRadiusKm, ...
    config.speedOfLightKmPerSec);
above = gravitationalTimeDilationModel( ...
    [config.earthRadiusKm+500;config.earthRadiusKm+500],time, ...
    config.muEarthKm3PerSec2,config.earthRadiusKm, ...
    config.speedOfLightKmPerSec);
altitudes = [500;20000;40000];
radii = config.earthRadiusKm+altitudes;
increasing = gravitationalTimeDilationModel( ...
    radii,[0;1;2],config.muEarthKm3PerSec2,config.earthRadiusKm, ...
    config.speedOfLightKmPerSec);
gps = analysis.gpsBenchmark;
gpsHistory = analysis.histories([analysis.histories.name]== ...
    "Theoretical GPS 20,200 km circular");
gpsModel = gpsHistory.relativity;
constantAnalyticalSeconds = ...
    gpsModel.netApproximateClockRateCorrection(1)*config.durationSeconds;
constantIntegrationError = abs( ...
    gpsModel.accumulatedNetApproximateSeconds(end)- ...
    constantAnalyticalSeconds);
unitError = max(abs(gpsModel.gravitational.accumulatedMicroseconds- ...
    gpsModel.gravitational.accumulatedSeconds*1e6));
crossoverAltitude = analysis.crossover.altitudeKmAnalytical;
crossoverRadius = config.earthRadiusKm+crossoverAltitude;
crossoverSpeed = sqrt(config.muEarthKm3PerSec2/crossoverRadius);
crossoverModel = combinedRelativisticClockModel( ...
    [crossoverRadius;crossoverRadius],[crossoverSpeed;crossoverSpeed], ...
    [0;config.secondsPerDay],config.muEarthKm3PerSec2, ...
    config.earthRadiusKm,config.speedOfLightKmPerSec);
belowIndex = find(analysis.crossover.altitudeKm<crossoverAltitude,1,'last');
aboveIndex = find(analysis.crossover.altitudeKm>crossoverAltitude,1,'first');
elliptical = analysis.ellipticalVerification;
ellipticalRelativeError = abs(elliptical.netIntegrationErrorSeconds/ ...
    elliptical.netAnalyticalSeconds);
repeat = combinedRelativisticClockModel(gpsHistory.positionKm, ...
    gpsHistory.velocityKmPerSec,gpsHistory.elapsedSeconds, ...
    config.muEarthKm3PerSec2,config.earthRadiusKm, ...
    config.speedOfLightKmPerSec, ...
    ReferenceClockConvention=config.referenceClockConvention, ...
    CoordinateTimeConvention=config.coordinateTimeConvention);
reproducibilityError = max(abs(repeat.accumulatedNetApproximateSeconds- ...
    gpsModel.accumulatedNetApproximateSeconds));
utcTimes = datetime(2026,1,1,0,0,[0 1],'TimeZone','UTC').';
datetimeModel = gravitationalTimeDilationModel( ...
    [config.earthRadiusKm+500;config.earthRadiusKm+500],utcTimes, ...
    config.muEarthKm3PerSec2,config.earthRadiusKm, ...
    config.speedOfLightKmPerSec);
allFinite = all(isfinite(analysis.timeSeries{:,4:end}),'all');

testName = [ ...
    "Zero potential difference gives zero gravitational correction"; ...
    "Satellite above surface has positive gravitational correction"; ...
    "Gravitational advantage increases with altitude"; ...
    "Kinematic correction has the negative sign"; ...
    "GPS gravitational correction is near +45.7 microseconds/day"; ...
    "GPS kinematic correction is near -7.2 microseconds/day"; ...
    "GPS net correction is near +38.5 microseconds/day"; ...
    "Constant-rate numerical integral matches analytical solution"; ...
    "Second-to-microsecond conversion is consistent"; ...
    "Circular crossover rate is zero under stated assumptions"; ...
    "Net drift changes from negative to positive at crossover"; ...
    "Elliptical one-orbit integration matches analytical average"; ...
    "Combined calculation is exactly reproducible"; ...
    "At least five timing scenarios are analyzed"; ...
    "At least five real satellites are analyzed"; ...
    "All exported numerical histories are finite"; ...
    "Timezone-aware datetime input is supported"; ...
    "Reference-clock convention is explicitly documented"];
measuredValue = [ ...
    max(abs(surface.clockRateCorrection)); ...
    min(above.clockRateCorrection); ...
    double(all(diff(increasing.clockRateCorrection)>0)); ...
    max(gpsModel.kinematic.approximateClockRateCorrection); ...
    abs(gps.gravitationalMicrosecondsPerDay-45.7); ...
    abs(gps.kinematicMicrosecondsPerDay+7.2); ...
    abs(gps.netMicrosecondsPerDay-38.5); ...
    constantIntegrationError;unitError; ...
    abs(crossoverModel.netApproximateClockRateCorrection(1)); ...
    double(analysis.crossover.netMicrosecondsPerDay(belowIndex)<0 && ...
        analysis.crossover.netMicrosecondsPerDay(aboveIndex)>0); ...
    ellipticalRelativeError;reproducibilityError; ...
    analysis.scenarioCount;analysis.realSatelliteCount;double(allFinite); ...
    double(datetimeModel.inputTimeType=="datetime"); ...
    double(strlength(analysis.referenceClockConvention)>20)];
comparison = ["<=";">";"==";"<";"<=";"<=";"<=";"<=";"<="; ...
    "<=";"==";"<=";"<=";">=";">=";"==";"==";"=="];
criterion = [0;0;1;0;0.2;0.15;0.25;1e-15;1e-12;1e-20;1;1e-6;0;5;5;1;1;1];
passed = [measuredValue(1)<=criterion(1);measuredValue(2)>criterion(2); ...
    measuredValue(3)==criterion(3);measuredValue(4)<criterion(4); ...
    measuredValue(5)<=criterion(5);measuredValue(6)<=criterion(6); ...
    measuredValue(7)<=criterion(7);measuredValue(8)<=criterion(8); ...
    measuredValue(9)<=criterion(9);measuredValue(10)<=criterion(10); ...
    measuredValue(11)==criterion(11);measuredValue(12)<=criterion(12); ...
    measuredValue(13)<=criterion(13);measuredValue(14)>=criterion(14); ...
    measuredValue(15)>=criterion(15);measuredValue(16)==criterion(16); ...
    measuredValue(17)==criterion(17);measuredValue(18)==criterion(18)];
unit = ["dimensionless";"dimensionless";"logical";"dimensionless"; ...
    "microseconds/day";"microseconds/day";"microseconds/day";"seconds"; ...
    "microseconds";"dimensionless";"logical";"relative";"seconds"; ...
    "scenarios";"satellites";"logical";"logical";"logical"];
results = table(testName,measuredValue,comparison,criterion,unit,passed, ...
    'VariableNames',{'Test','MeasuredValue','Comparison','Criterion','Unit','Passed'});
report = struct('results',results,'passedTests',sum(passed), ...
    'totalTests',height(results),'allPassed',all(passed));
if ~report.allPassed
    error('runDay09RelativityTests:VerificationFailure','Failed checks: %s.', ...
        strjoin(cellstr(testName(~passed)),', '));
end
end
