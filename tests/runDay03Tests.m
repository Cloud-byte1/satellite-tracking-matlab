function report = runDay03Tests(runs, constants)
%RUNDAY03TESTS Execute engineering verification for all Day 3 scenarios.
%   Each tolerance is stated explicitly in the saved results table.

arguments
    runs (:,1) struct
    constants (1,1) struct
end

analyses = [runs.analysis];
scenarioCount = numel(runs);

% Round-trip a nonsingular state so all six classical angles are defined.
reference = runs(4).scenario;
[referencePosition, referenceVelocity] = orbitalElementsToState( ...
    reference, constants.muEarth);
recovered = stateToOrbitalElements(referencePosition, referenceVelocity, ...
    constants.muEarth);
[roundTripPosition, roundTripVelocity] = orbitalElementsToState( ...
    recovered, constants.muEarth);

roundTripPositionErrorKm = norm(roundTripPosition - referencePosition);
roundTripVelocityErrorKmPerSec = norm(roundTripVelocity - referenceVelocity);

leo = runs(1);
leoAnalyticalSpeed = sqrt(constants.muEarth/leo.scenario.aKm);
leoCircularSpeedError = abs(norm(leo.solution.velocity(1,:)) - leoAnalyticalSpeed);

periodEndpointErrors = zeros(scenarioCount,1);
perigeeErrors = zeros(scenarioCount,1);
apogeeErrors = zeros(scenarioCount,1);
minimumSpeedErrors = zeros(scenarioCount,1);
maximumSpeedErrors = zeros(scenarioCount,1);
eccentricityErrors = zeros(scenarioCount,1);
closureErrors = zeros(scenarioCount,1);
energyDrifts = zeros(scenarioCount,1);
angularMomentumDrifts = zeros(scenarioCount,1);

for index = 1:scenarioCount
    item = analyses(index);
    periodEndpointErrors(index) = abs( ...
        runs(index).solution.time(end) - item.periodSec);
    perigeeErrors(index) = abs(item.numericalPerigeeAltitudeKm ...
        - item.perigeeAltitudeKm);
    apogeeErrors(index) = abs(item.numericalApogeeAltitudeKm ...
        - item.apogeeAltitudeKm);
    minimumSpeedErrors(index) = abs(item.numericalMinimumSpeedKmPerSec ...
        - item.minimumSpeedKmPerSec);
    maximumSpeedErrors(index) = abs(item.numericalMaximumSpeedKmPerSec ...
        - item.maximumSpeedKmPerSec);
    eccentricityErrors(index) = abs(item.eccentricityFromState ...
        - runs(index).scenario.e);
    closureErrors(index) = item.positionClosureErrorKm;
    energyDrifts(index) = item.maxRelativeEnergyDrift;
    angularMomentumDrifts(index) = item.maxRelativeAngularMomentumDrift;
end

testName = [ ...
    "COE-state-COE position round trip"; ...
    "COE-state-COE velocity round trip"; ...
    "LEO circular speed versus sqrt(mu/r)"; ...
    "Kepler period endpoint across scenarios"; ...
    "Perigee altitude consistency"; ...
    "Apogee altitude consistency"; ...
    "Minimum speed versus vis-viva"; ...
    "Maximum speed versus vis-viva"; ...
    "Eccentricity recovered from state"; ...
    "One-period position closure"; ...
    "Specific energy conservation"; ...
    "Angular momentum conservation"];
measuredValue = [ ...
    roundTripPositionErrorKm; ...
    roundTripVelocityErrorKmPerSec; ...
    leoCircularSpeedError; ...
    max(periodEndpointErrors); ...
    max(perigeeErrors); ...
    max(apogeeErrors); ...
    max(minimumSpeedErrors); ...
    max(maximumSpeedErrors); ...
    max(eccentricityErrors); ...
    max(closureErrors); ...
    max(energyDrifts); ...
    max(angularMomentumDrifts)];
tolerance = [1e-8; 1e-11; 1e-12; 1e-9; 1e-4; 1e-4; ...
    1e-7; 1e-7; 1e-12; 1e-2; 1e-9; 1e-9];
unit = ["km"; "km/s"; "km/s"; "s"; "km"; "km"; "km/s"; ...
    "km/s"; "dimensionless"; "km"; "relative"; "relative"];
passed = measuredValue <= tolerance;

results = table(testName, measuredValue, tolerance, unit, passed, ...
    'VariableNames', {'Test', 'MeasuredValue', 'Tolerance', 'Unit', 'Passed'});
report = struct('results', results, 'totalTests', height(results), ...
    'passedTests', sum(passed), 'allPassed', all(passed));

if ~report.allPassed
    failedNames = strjoin(cellstr(testName(~passed)), ', ');
    error('runDay03Tests:VerificationFailure', ...
        'Day 3 verification failed: %s', failedNames);
end
end
