function report = runSatelliteScenarioTests(scenario,satellites,tleCatalog,expectedCount)
%RUNSATELLITESCENARIOTESTS Verify the native satelliteScenario integration.

[positionMeters,velocityMetersPerSecond] = states(satellites,scenario.StartTime);
positionMeters = reshape(positionMeters,3,[]).';
velocityMetersPerSecond = reshape(velocityMetersPerSecond,3,[]).';
radiusKm = vecnorm(positionMeters,2,2)/1000;
speedKmPerSec = vecnorm(velocityMetersPerSecond,2,2)/1000;
propagators = strings(numel(satellites),1);
for index = 1:numel(satellites)
    propagators(index) = string(satellites(index).OrbitPropagator);
end

testName = [ ...
    "Expected real satellites loaded"; ...
    "All native propagators use SGP4 or SDP4"; ...
    "Initial positions are finite"; ...
    "Initial velocities are finite"; ...
    "Initial radii remain above Earth"; ...
    "Initial orbital speeds are plausible"; ...
    "Catalog identifiers remain unique"; ...
    "Scenario timeline advances forward"];
measuredValue = [ ...
    numel(satellites); ...
    sum(ismember(propagators,["sgp4","sdp4"])); ...
    double(all(isfinite(positionMeters),'all')); ...
    double(all(isfinite(velocityMetersPerSecond),'all')); ...
    min(radiusKm); ...
    max(speedKmPerSec); ...
    numel(unique(tleCatalog.NORADCatalogID)); ...
    seconds(scenario.StopTime-scenario.StartTime)];
criterion = [expectedCount;expectedCount;1;1;6478;15;expectedCount;1];
comparison = ["==";"==";"==";"==";">";"<";"==";">"];
passed = [ ...
    measuredValue(1) == criterion(1); ...
    measuredValue(2) == criterion(2); ...
    measuredValue(3) == criterion(3); ...
    measuredValue(4) == criterion(4); ...
    measuredValue(5) > criterion(5); ...
    measuredValue(6) < criterion(6); ...
    measuredValue(7) == criterion(7); ...
    measuredValue(8) > criterion(8)];
unit = ["satellites";"satellites";"logical";"logical"; ...
    "km";"km/s";"IDs";"s"];
results = table(testName,measuredValue,comparison,criterion,unit,passed, ...
    'VariableNames',{'Test','MeasuredValue','Comparison','Criterion','Unit','Passed'});
report = struct('results',results,'passedTests',sum(passed), ...
    'totalTests',height(results),'allPassed',all(passed));
if ~report.allPassed
    failed = strjoin(cellstr(testName(~passed)),', ');
    error('runSatelliteScenarioTests:VerificationFailure', ...
        'Native satelliteScenario verification failed: %s',failed);
end
end
