function report = runDay08RelativityTests(analysis,config)
%RUNDAY08RELATIVITYTESTS Verify physics, units, integration, and inputs.

zero = specialRelativisticClockModel([0;0],[0;1], ...
    config.speedOfLightKmPerSec);
ordered = specialRelativisticClockModel([0;3;7.8],[0;1;2], ...
    config.speedOfLightKmPerSec);
gps = analysis.gpsBenchmark;
gpsHistory = analysis.histories( ...
    [analysis.histories.name]=="Theoretical GPS 20,200 km circular");
constantAnalyticalSeconds = gpsHistory.clock.exactClockRateCorrection(1)* ...
    config.durationSeconds;
constantIntegrationError = abs( ...
    gpsHistory.clock.accumulatedExactSeconds(end)-constantAnalyticalSeconds);
unitConversionError = max(abs( ...
    gpsHistory.clock.accumulatedExactMicroseconds- ...
    gpsHistory.clock.accumulatedExactSeconds*1e6));
orbitalRelativeFormulaError = max(abs( ...
    gpsHistory.clock.exactClockRateCorrection- ...
    gpsHistory.clock.approximateClockRateCorrection)./ ...
    abs(gpsHistory.clock.exactClockRateCorrection));
elliptical = analysis.ellipticalVerification;
repeat = specialRelativisticClockModel(gpsHistory.velocityKmPerSec, ...
    gpsHistory.elapsedSeconds,config.speedOfLightKmPerSec, ...
    CoordinateTimeConvention=config.coordinateTimeConvention);
reproducibilityError = max(abs(repeat.accumulatedExactSeconds- ...
    gpsHistory.clock.accumulatedExactSeconds));
allFinite = true; allNonpositive = true;
for index = 1:numel(analysis.histories)
    rate = analysis.histories(index).clock.exactClockRateCorrection;
    allFinite = allFinite && all(isfinite(rate)) && ...
        all(isfinite(analysis.histories(index).clock.accumulatedExactSeconds));
    allNonpositive = allNonpositive && all(rate<=0);
end
stepError = max(abs(diff(gpsHistory.elapsedSeconds)-config.stepSeconds));

testName = ["Zero velocity gives zero correction"; ...
    "Increasing speed makes correction more negative"; ...
    "Second-to-microsecond conversion is consistent"; ...
    "Exact and low-velocity rates agree in orbit"; ...
    "GPS benchmark is near -7.2 microseconds/day"; ...
    "Constant-speed numerical integral is analytical"; ...
    "Elliptical perigee speed exceeds apogee speed"; ...
    "Elliptical perigee correction is more negative"; ...
    "Elliptical orbit average matches analytical estimate"; ...
    "Clock calculation is reproducible"; ...
    "At least five scenarios are analyzed"; ...
    "At least five real satellites are integrated"; ...
    "All clock histories are finite and nonpositive"; ...
    "Trajectory timestamps preserve the 60-second step"; ...
    "Input velocity frame is documented as J2000/FK5"];
measuredValue = [max(abs(zero.exactClockRateCorrection)); ...
    double(all(diff(ordered.exactClockRateCorrection)<0)); ...
    unitConversionError;orbitalRelativeFormulaError; ...
    abs(gps.IntegratedDrift24HoursMicroseconds+7.2); ...
    constantIntegrationError; ...
    elliptical.perigeeSpeedKmPerSec-elliptical.apogeeSpeedKmPerSec; ...
    elliptical.apogeeRateCorrection-elliptical.perigeeRateCorrection; ...
    elliptical.relativeIntegrationError;reproducibilityError; ...
    analysis.scenarioCount;analysis.realSatelliteCount; ...
    double(allFinite&&allNonpositive);stepError; ...
    double(contains(string(analysis.referenceFrame),"J2000/FK5"))];
comparisonOperator = ["<=";"==";"<=";"<=";"<=";"<=";">";">"; ...
    "<=";"<=";">=";">=";"==";"<=";"=="];
criterion = [0;1;1e-12;1e-8;0.15;1e-15;0;0;1e-6;0;5;5;1;1e-12;1];
passed = [measuredValue(1)<=criterion(1);measuredValue(2)==criterion(2); ...
    measuredValue(3)<=criterion(3);measuredValue(4)<=criterion(4); ...
    measuredValue(5)<=criterion(5);measuredValue(6)<=criterion(6); ...
    measuredValue(7)>criterion(7);measuredValue(8)>criterion(8); ...
    measuredValue(9)<=criterion(9);measuredValue(10)<=criterion(10); ...
    measuredValue(11)>=criterion(11);measuredValue(12)>=criterion(12); ...
    measuredValue(13)==criterion(13);measuredValue(14)<=criterion(14); ...
    measuredValue(15)==criterion(15)];
unit = ["dimensionless";"logical";"microseconds";"relative"; ...
    "microseconds/day";"seconds";"km/s";"dimensionless";"relative"; ...
    "seconds";"scenarios";"satellites";"logical";"seconds";"logical"];
results = table(testName,measuredValue,comparisonOperator,criterion,unit,passed, ...
    'VariableNames',{'Test','MeasuredValue','Comparison','Criterion','Unit','Passed'});
report = struct('results',results,'passedTests',sum(passed), ...
    'totalTests',height(results),'allPassed',all(passed));
if ~report.allPassed
    error('runDay08RelativityTests:VerificationFailure','Failed checks: %s.', ...
        strjoin(cellstr(testName(~passed)),', '));
end
end
