function report = runDay01Tests(solution, analytical, diagnostics)
%RUNDAY01TESTS Execute quantitative verification checks for Day 1.
%   Tests intentionally use explicit engineering tolerances so their physical
%   meaning remains visible in the saved report.

initialState = solution.state(1,:).';
finalState = solution.state(end,:).';

positionClosureErrorKm = norm(finalState(1:3) - initialState(1:3));
velocityClosureErrorKmPerSec = norm(finalState(4:6) - initialState(4:6));
initialSpeedErrorKmPerSec = abs(norm(initialState(4:6)) - analytical.speed);
periodErrorSec = abs(solution.time(end) - analytical.period);

% Independent tighter-tolerance propagation for a numerical convergence check.
tightSolution = propagateTwoBody(initialState, solution.time, solution.mu, ...
    RelativeTolerance=1e-13, AbsoluteTolerance=1e-14, ...
    MaximumStep=analytical.period/400);
convergencePositionErrorKm = norm( ...
    solution.state(end,1:3) - tightSolution.state(end,1:3));

testName = [ ...
    "Initial circular speed"; ...
    "Requested period endpoint"; ...
    "One-orbit position closure"; ...
    "One-orbit velocity closure"; ...
    "Specific energy conservation"; ...
    "Angular momentum conservation"; ...
    "Tight-solution convergence"];

measuredValue = [ ...
    initialSpeedErrorKmPerSec; ...
    periodErrorSec; ...
    positionClosureErrorKm; ...
    velocityClosureErrorKmPerSec; ...
    diagnostics.maxRelativeEnergyDrift; ...
    diagnostics.maxRelativeAngularMomentumDrift; ...
    convergencePositionErrorKm];

tolerance = [1e-12; 1e-10; 1e-4; 1e-7; 1e-9; 1e-9; 1e-3];
unit = ["km/s"; "s"; "km"; "km/s"; "dimensionless"; ...
    "dimensionless"; "km"];
passed = measuredValue <= tolerance;

results = table(testName, measuredValue, tolerance, unit, passed, ...
    'VariableNames', {'Test', 'MeasuredValue', 'Tolerance', 'Unit', 'Passed'});

report = struct();
report.results = results;
report.totalTests = height(results);
report.passedTests = sum(passed);
report.allPassed = all(passed);
report.convergencePositionErrorKm = convergencePositionErrorKm;
report.positionClosureErrorKm = positionClosureErrorKm;
report.velocityClosureErrorKmPerSec = velocityClosureErrorKmPerSec;

if ~report.allPassed
    failedNames = strjoin(cellstr(testName(~passed)), ', ');
    error('runDay01Tests:VerificationFailure', ...
        'Day 1 verification failed: %s', failedNames);
end
end

