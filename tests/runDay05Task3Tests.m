function report = runDay05Task3Tests(catalog, targets)
%RUNDAY05TASK3TESTS Verify composition and required fields of live catalog.

requiredCatalogFields = ["SatelliteName", "NORADCatalogID", "MissionRole", ...
    "Constellation", "ElementEpochUtc", "InclinationDeg", "Eccentricity", ...
    "MeanMotionRevPerDay", "ApproximatePeriodMinutes", "RetrievalTimeUtc", ...
    "ElementAgeHours", "RetrievalSource"];
hasRequiredFields = isempty(setdiff(requiredCatalogFields, ...
    string(catalog.Properties.VariableNames)));

expectedIds = sort(targets.CatalogNumber);
actualIds = sort(catalog.NORADCatalogID);
namesMatch = true;
for index = 1:height(targets)
    row = catalog.NORADCatalogID == targets.CatalogNumber(index);
    namesMatch = namesMatch && sum(row) == 1 && ~isempty(regexpi( ...
        catalog.SatelliteName(row), targets.ExpectedNamePattern(index), 'once'));
end

testName = [ ...
    "Catalog contains five real satellites"; ...
    "Catalog IDs exactly match the approved target list"; ...
    "Catalog IDs are unique"; ...
    "ISS is present"; ...
    "At least two GPS satellites are present"; ...
    "At least two additional non-GPS satellites are present"; ...
    "At least four mission groups are represented"; ...
    "Returned names agree with stable catalog IDs"; ...
    "All required Task 3 fields are present"; ...
    "All timestamps are explicit UTC datetimes"; ...
    "Mean-motion period conversion is correct"];

periodErrorMinutes = max(abs(catalog.ApproximatePeriodMinutes ...
    - 1440./catalog.MeanMotionRevPerDay));
passed = [ ...
    height(catalog) == 5; ...
    isequal(actualIds, expectedIds); ...
    numel(unique(catalog.NORADCatalogID)) == height(catalog); ...
    sum(catalog.NORADCatalogID == 25544) == 1; ...
    sum(catalog.Constellation == "GPS") >= 2; ...
    sum(catalog.Constellation ~= "GPS" & catalog.NORADCatalogID ~= 25544) >= 2; ...
    numel(unique(catalog.Constellation)) >= 4; ...
    namesMatch; ...
    hasRequiredFields; ...
    isdatetime(catalog.ElementEpochUtc) && ...
        ~isempty(catalog.ElementEpochUtc.TimeZone) && ...
        isdatetime(catalog.RetrievalTimeUtc) && ...
        ~isempty(catalog.RetrievalTimeUtc.TimeZone); ...
    periodErrorMinutes <= 1e-12];

measuredValue = [height(catalog); double(isequal(actualIds, expectedIds)); ...
    numel(unique(catalog.NORADCatalogID)); ...
    sum(catalog.NORADCatalogID == 25544); ...
    sum(catalog.Constellation == "GPS"); ...
    sum(catalog.Constellation ~= "GPS" & catalog.NORADCatalogID ~= 25544); ...
    numel(unique(catalog.Constellation)); double(namesMatch); ...
    double(hasRequiredFields); ...
    double(isdatetime(catalog.ElementEpochUtc) && ...
        ~isempty(catalog.ElementEpochUtc.TimeZone) && ...
        isdatetime(catalog.RetrievalTimeUtc) && ...
        ~isempty(catalog.RetrievalTimeUtc.TimeZone)); ...
    periodErrorMinutes];
unit = ["records"; "logical"; "IDs"; "records"; "records"; "records"; ...
    "groups"; "logical"; "logical"; "logical"; "minutes"];

results = table(testName, measuredValue, unit, passed, ...
    'VariableNames', {'Test','MeasuredValue','Unit','Passed'});
report = struct('results', results, 'totalTests', height(results), ...
    'passedTests', sum(passed), 'allPassed', all(passed));
if ~report.allPassed
    failedNames = strjoin(cellstr(testName(~passed)), ', ');
    error('runDay05Task3Tests:VerificationFailure', ...
        'Day 5 Task 3 tests failed: %s', failedNames);
end
end
