function report = runDay02Task1Tests(catalog, config)
%RUNDAY02TASK1TESTS Verify the Day 2 catalog and CelesTrak data contract.

issUrl = buildCelesTrakGpUrl("CATNR", ...
    string(config.issCatalogNumber), config.primaryFormat, config.baseUrl);
gpsUrl = buildCelesTrakGpUrl("GROUP", config.gpsGroup, ...
    config.primaryFormat, config.baseUrl);

testName = [ ...
    "Catalog contains five satellites"; ...
    "Catalog contains the ISS"; ...
    "Catalog contains four GPS satellites"; ...
    "Catalog numbers are unique"; ...
    "Primary format is OMM-compatible CSV"; ...
    "Queries use official HTTPS endpoint"];

passed = [ ...
    height(catalog) == 5; ...
    sum(catalog.CatalogNumber == config.issCatalogNumber) == 1; ...
    sum(catalog.Role == "GPS") == 4; ...
    numel(unique(catalog.CatalogNumber)) == height(catalog); ...
    config.primaryFormat == "CSV"; ...
    startsWith(issUrl, "https://celestrak.org/") && ...
        startsWith(gpsUrl, "https://celestrak.org/")];

results = table(testName, passed, ...
    'VariableNames', {'Test', 'Passed'});

report = struct();
report.results = results;
report.totalTests = height(results);
report.passedTests = sum(passed);
report.allPassed = all(passed);
report.issUrl = issUrl;
report.gpsUrl = gpsUrl;

if ~report.allPassed
    failedNames = strjoin(cellstr(testName(~passed)), ', ');
    error('runDay02Task1Tests:VerificationFailure', ...
        'Day 2 Task 1 verification failed: %s', failedNames);
end
end

