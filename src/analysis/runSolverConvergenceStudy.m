function study = runSolverConvergenceStudy(comparison,config)
%RUNSOLVERCONVERGENCESTUDY Compare ode45 tolerances against a tight solution.

durationSeconds = config.convergenceDurationHours*3600;
times = linspace(0,durationSeconds,361).';
initialState = [comparison.positionSgp4J2000Km(1,:,1) ...
    comparison.velocitySgp4J2000KmPerSec(1,:,1)].';
reference = propagateTwoBody(initialState,times, ...
    comparison.twoBodyMuKm3PerSec2, ...
    RelativeTolerance=config.convergenceReferenceTolerance, ...
    AbsoluteTolerance=config.convergenceReferenceTolerance*0.1, ...
    MaximumStep=config.convergenceMaximumStepSeconds/2);

tolerances = config.convergenceRelativeTolerances(:);
count = numel(tolerances);
FinalPositionDifferenceMeters = zeros(count,1);
MaximumPositionDifferenceMeters = zeros(count,1);
RuntimeSeconds = zeros(count,1);
for index = 1:count
    timer = tic;
    candidate = propagateTwoBody(initialState,times, ...
        comparison.twoBodyMuKm3PerSec2, ...
        RelativeTolerance=tolerances(index), ...
        AbsoluteTolerance=tolerances(index)*0.1, ...
        MaximumStep=config.convergenceMaximumStepSeconds);
    RuntimeSeconds(index) = toc(timer);
    differenceMeters = vecnorm(candidate.position-reference.position,2,2)*1000;
    FinalPositionDifferenceMeters(index) = differenceMeters(end);
    MaximumPositionDifferenceMeters(index) = max(differenceMeters);
end
study = table(tolerances,FinalPositionDifferenceMeters, ...
    MaximumPositionDifferenceMeters,RuntimeSeconds, ...
    'VariableNames',{'RelativeTolerance', ...
    'FinalPositionDifferenceMeters','MaximumPositionDifferenceMeters', ...
    'RuntimeSeconds'});
end
