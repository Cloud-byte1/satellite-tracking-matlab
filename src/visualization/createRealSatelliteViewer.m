function figureHandle = createRealSatelliteViewer(simulation, earthRadiusKm, options)
%CREATEREALSATELLITEVIEWER Interactive five-satellite TEME animation.
%   The viewer provides play/pause, a timeline slider, playback speed, clickable
%   satellite markers, and a live time/position inspector. Earth is centered in
%   TEME; no Earth-fixed latitude/longitude map is implied.

arguments
    simulation (1,1) struct
    earthRadiusKm (1,1) double {mustBePositive, mustBeFinite}
    options.Visible (1,1) logical = true
end

colors = lines(numel(simulation.catalogIds));
visibility = matlab.lang.OnOffSwitchState(options.Visible);
figureHandle = figure('Color','white', 'Name', ...
    'Real Satellite SGP4 Simulation (TEME)', 'Position',[40 60 1500 850], ...
    'Visible',visibility);
axesHandle = axes(figureHandle, 'Position',[0.04 0.12 0.60 0.81]);
hold(axesHandle,'on');
set(axesHandle,'Color','white','XColor',[0.15 0.15 0.15], ...
    'YColor',[0.15 0.15 0.15],'ZColor',[0.15 0.15 0.15], ...
    'GridColor',[0.72 0.72 0.72],'GridAlpha',0.45);

[earthX,earthY,earthZ] = sphere(100);
earthSurface = surf(axesHandle, earthRadiusKm*earthX, earthRadiusKm*earthY, ...
    earthRadiusKm*earthZ, 'FaceColor',[0.10 0.36 0.62], ...
    'EdgeColor','none','FaceAlpha',0.86,'DisplayName','Earth');
satelliteCount = numel(simulation.catalogIds);
pathHandles = gobjects(satelliteCount,1);
markerHandles = gobjects(satelliteCount,1);
labelHandles = gobjects(satelliteCount,1);
maximumRadius = earthRadiusKm;

for index = 1:satelliteCount
    position = simulation.positionTemeKm(:,:,index);
    maximumRadius = max(maximumRadius,max(vecnorm(position,2,2)));
    pathHandles(index) = plot3(axesHandle,position(:,1),position(:,2),position(:,3), ...
        '-','Color',colors(index,:),'LineWidth',1.25, ...
        'DisplayName',simulation.satelliteNames(index));
    markerHandles(index) = plot3(axesHandle,position(1,1),position(1,2),position(1,3), ...
        'o','Color',colors(index,:),'MarkerFaceColor',colors(index,:), ...
        'MarkerSize',8,'HandleVisibility','off','PickableParts','all', ...
        'HitTest','on','ButtonDownFcn',@(~,~) selectSatellite(index));
    labelHandles(index) = text(axesHandle,position(1,1),position(1,2),position(1,3), ...
        "  " + simulation.satelliteNames(index),'Color',colors(index,:), ...
        'FontSize',8,'FontWeight','bold','HandleVisibility','off');
end

axis(axesHandle,'equal'); grid(axesHandle,'on'); box(axesHandle,'on');
limit = 1.08*maximumRadius;
xlim(axesHandle,[-limit limit]); ylim(axesHandle,[-limit limit]);
zlim(axesHandle,[-limit limit]);
xlabel(axesHandle,'TEME x (km)'); ylabel(axesHandle,'TEME y (km)');
zlabel(axesHandle,'TEME z (km)'); view(axesHandle,35,24);
camlight(axesHandle,'headlight'); lighting(axesHandle,'gouraud');
legend(axesHandle,[earthSurface;pathHandles],'Location','eastoutside');

sampleCount = numel(simulation.timeUtc);
selectedSatellite = 1;
playButton = uicontrol(figureHandle,'Style','togglebutton','String','Play', ...
    'Units','normalized','Position',[0.08 0.025 0.08 0.045], ...
    'Callback',@playCallback);
sliderHandle = uicontrol(figureHandle,'Style','slider','Min',1,'Max',sampleCount, ...
    'Value',1,'SliderStep',[1/max(1,sampleCount-1),10/max(1,sampleCount-1)], ...
    'Units','normalized','Position',[0.18 0.03 0.47 0.035], ...
    'Callback',@sliderCallback);
speedMenu = uicontrol(figureHandle,'Style','popupmenu', ...
    'String',{'1x','2x','5x','10x','30x'},'Value',2,'Units','normalized', ...
    'Position',[0.67 0.026 0.08 0.043]);
timeLabel = uicontrol(figureHandle,'Style','text','BackgroundColor','white', ...
    'ForegroundColor',[0.10 0.10 0.10],'FontWeight','bold', ...
    'HorizontalAlignment','left','Units','normalized', ...
    'Position',[0.76 0.025 0.22 0.045]);

uicontrol(figureHandle,'Style','text','String','OBSERVE A SATELLITE', ...
    'BackgroundColor','white','ForegroundColor',[0.10 0.25 0.45], ...
    'FontWeight','bold','FontSize',11,'HorizontalAlignment','left', ...
    'Units','normalized','Position',[0.77 0.83 0.20 0.04]);
satelliteMenu = uicontrol(figureHandle,'Style','popupmenu', ...
    'String',cellstr(simulation.satelliteNames),'Value',1, ...
    'Units','normalized','Position',[0.77 0.78 0.20 0.045], ...
    'Callback',@satelliteMenuCallback);
stateReadout = uicontrol(figureHandle,'Style','text','BackgroundColor',[0.96 0.98 1], ...
    'ForegroundColor',[0.08 0.12 0.20],'HorizontalAlignment','left', ...
    'FontName','Consolas','FontSize',10,'Units','normalized', ...
    'Position',[0.77 0.31 0.20 0.46]);
uicontrol(figureHandle,'Style','text','BackgroundColor','white', ...
    'ForegroundColor',[0.35 0.35 0.35],'HorizontalAlignment','left', ...
    'String',sprintf(['Drag the timeline to move every satellite.\n' ...
    'Click a satellite marker to select it.\n' ...
    'The readout is TEME, not latitude/longitude.']), ...
    'Units','normalized','Position',[0.77 0.18 0.20 0.10]);
rotate3d(figureHandle,'on');
setappdata(figureHandle,'SatelliteTrackingControls',struct( ...
    'Axes',axesHandle,'PlayButton',playButton,'TimelineSlider',sliderHandle, ...
    'SpeedMenu',speedMenu,'SatelliteMenu',satelliteMenu, ...
    'TimeLabel',timeLabel,'StateReadout',stateReadout, ...
    'MarkerHandles',markerHandles));
updateFrame(1);
selectSatellite(1);

    function sliderCallback(~,~)
        updateFrame(round(sliderHandle.Value));
    end

    function playCallback(~,~)
        if playButton.Value
            playButton.String = 'Pause';
        end
        frameSteps = [1 2 5 10 30];
        while isvalid(figureHandle) && playButton.Value
            nextIndex = round(sliderHandle.Value) + frameSteps(speedMenu.Value);
            if nextIndex > sampleCount
                nextIndex = 1;
            end
            sliderHandle.Value = nextIndex;
            updateFrame(nextIndex);
            drawnow;
            pause(0.035);
        end
        if isvalid(figureHandle)
            playButton.String = 'Play';
        end
    end

    function satelliteMenuCallback(~,~)
        selectSatellite(satelliteMenu.Value);
    end

    function selectSatellite(index)
        selectedSatellite = index;
        satelliteMenu.Value = index;
        for item = 1:satelliteCount
            if item == selectedSatellite
                markerHandles(item).MarkerSize = 12;
                markerHandles(item).LineWidth = 2;
                labelHandles(item).FontSize = 10;
            else
                markerHandles(item).MarkerSize = 8;
                markerHandles(item).LineWidth = 0.5;
                labelHandles(item).FontSize = 8;
            end
        end
        updateReadout(round(sliderHandle.Value));
    end

    function updateFrame(frameIndex)
        for satellite = 1:satelliteCount
            position = simulation.positionTemeKm(frameIndex,:,satellite);
            set(markerHandles(satellite),'XData',position(1), ...
                'YData',position(2),'ZData',position(3));
            set(labelHandles(satellite),'Position',position);
        end
        timestamp = string(simulation.timeUtc(frameIndex), ...
            "yyyy-MM-dd HH:mm:ss 'UTC'");
        titleHandle = title(axesHandle,{ ...
            'Five Real Satellites — SGP4 in TEME', ...
            char(timestamp + " | drag to rotate, scroll to zoom")});
        set(titleHandle,'Color',[0.10 0.10 0.10],'FontWeight','bold');
        timeLabel.String = sprintf('Frame %d/%d\n%s', ...
            frameIndex,sampleCount,timestamp);
        updateReadout(frameIndex);
    end

    function updateReadout(frameIndex)
        observation = observeSatelliteState(simulation,selectedSatellite, ...
            frameIndex,earthRadiusKm);
        position = observation.positionKm;
        velocity = observation.velocityKmPerSec;
        stateReadout.String = sprintf([ ...
            '%s\nNORAD %d\n\nTIME (UTC)\n%s\n\nPOSITION - TEME (km)\n' ...
            'X  %+12.3f\nY  %+12.3f\nZ  %+12.3f\n\n' ...
            'Altitude  %10.3f km\nSpeed     %10.6f km/s\n\n' ...
            'VELOCITY - TEME (km/s)\nX  %+10.6f\nY  %+10.6f\nZ  %+10.6f'], ...
            observation.name,observation.catalogId, ...
            string(observation.timeUtc,"yyyy-MM-dd HH:mm:ss 'UTC'"), ...
            position(1),position(2),position(3),observation.altitudeKm, ...
            observation.speedKmPerSec,velocity(1),velocity(2),velocity(3));
    end
end
