function figures = plotDay09RelativityFigures(analysis,config)
%PLOTDAY09RELATIVITYFIGURES Create four report-quality Day 9 figures.

figures = gobjects(4,1);
crossover = analysis.crossover;

figures(1) = figure('Color','white','Position',[70 70 1200 720], ...
    'Name','Day 9 Relativistic Drift Versus Altitude');
ax = axes(figures(1)); hold(ax,'on');
plot(ax,crossover.altitudeKm,crossover.gravitationalMicrosecondsPerDay, ...
    'LineWidth',2,'Color',[0.12 0.55 0.28],'DisplayName','Gravitational');
plot(ax,crossover.altitudeKm,crossover.kinematicMicrosecondsPerDay, ...
    'LineWidth',2,'Color',[0.78 0.20 0.18],'DisplayName','Kinematic');
plot(ax,crossover.altitudeKm,crossover.netMicrosecondsPerDay, ...
    'LineWidth',2.4,'Color',[0.08 0.30 0.62],'DisplayName','Net');
yline(ax,0,'k:','HandleVisibility','off');
xline(ax,crossover.altitudeKmAnalytical,'--','Crossover', ...
    'Color',[0.35 0.20 0.55],'LineWidth',1.4, ...
    'LabelOrientation','horizontal','HandleVisibility','off');
xline(ax,config.gpsAltitudeKm,'--','GPS altitude', ...
    'Color',[0.85 0.45 0.05],'LineWidth',1.4, ...
    'LabelOrientation','horizontal','HandleVisibility','off');
grid(ax,'on'); xlabel(ax,'Circular-orbit altitude (km)');
ylabel(ax,'Clock drift relative to surface reference (\mus/day)');
title(ax,'Relativistic Clock Drift Versus Circular-Orbit Altitude');
subtitle(ax,'Weak-field spherical Earth; stationary equatorial surface clock');
legend(ax,'Location','southeast');
applyReportTheme(figures(1));

gpsHistory = analysis.histories([analysis.histories.name]== ...
    "Theoretical GPS 20,200 km circular");
model = gpsHistory.relativity;
figures(2) = figure('Color','white','Position',[90 90 1180 700], ...
    'Name','Day 9 GPS Accumulated Correction');
ax = axes(figures(2)); hold(ax,'on');
plot(ax,model.elapsedSeconds/3600, ...
    model.gravitational.accumulatedMicroseconds,'LineWidth',2, ...
    'Color',[0.12 0.55 0.28],'DisplayName','Gravitational');
plot(ax,model.elapsedSeconds/3600, ...
    model.kinematic.accumulatedApproximateMicroseconds,'LineWidth',2, ...
    'Color',[0.78 0.20 0.18],'DisplayName','Kinematic');
plot(ax,model.elapsedSeconds/3600, ...
    model.accumulatedNetApproximateMicroseconds,'LineWidth',2.4, ...
    'Color',[0.08 0.30 0.62],'DisplayName','Net');
grid(ax,'on'); xlabel(ax,'Elapsed coordinate time (h)');
ylabel(ax,'Accumulated satellite-minus-reference time (\mus)');
title(ax,'Theoretical GPS Clock Correction Over 24 Hours');
subtitle(ax,'20,200 km circular orbit; leading-order benchmark');
legend(ax,'Location','northwest');
applyReportTheme(figures(2));

summary = analysis.summary;
figures(3) = figure('Color','white','Position',[110 70 1300 760], ...
    'Name','Day 9 Scenario Comparison');
ax = axes(figures(3));
values = [summary.GravitationalMicrosecondsPerDay, ...
    summary.KinematicMicrosecondsPerDay,summary.NetMicrosecondsPerDay];
barh(ax,values,'grouped');
grid(ax,'on'); set(ax,'YTick',1:height(summary), ...
    'YTickLabel',summary.ScenarioName,'TickLabelInterpreter','none', ...
    'YDir','reverse');
xlabel(ax,'Equivalent clock drift (\mus/day)');
ylabel(ax,'Satellite or orbital scenario');
title(ax,'Combined Relativistic Corrections Across Orbital Regimes');
subtitle(ax,'Real SGP4 trajectories and explicit theoretical comparison orbits');
legend(ax,{'Gravitational','Kinematic','Net'},'Location','southeast');
applyReportTheme(figures(3));

elliptical = analysis.ellipticalVerification;
elapsedHours = elliptical.model.elapsedSeconds/3600;
figures(4) = figure('Color','white','Position',[130 60 1220 800], ...
    'Name','Day 9 Elliptical Timing');
layout = tiledlayout(figures(4),2,1,'TileSpacing','compact','Padding','compact');
ax1 = nexttile(layout); hold(ax1,'on');
plot(ax1,elapsedHours, ...
    elliptical.model.gravitational.instantaneousMicrosecondsPerDay, ...
    'LineWidth',1.8,'Color',[0.12 0.55 0.28],'DisplayName','Gravitational');
plot(ax1,elapsedHours, ...
    elliptical.model.kinematic.instantaneousApproximateMicrosecondsPerDay, ...
    'LineWidth',1.8,'Color',[0.78 0.20 0.18],'DisplayName','Kinematic');
plot(ax1,elapsedHours, ...
    elliptical.model.instantaneousNetApproximateMicrosecondsPerDay, ...
    'LineWidth',2.2,'Color',[0.08 0.30 0.62],'DisplayName','Net');
grid(ax1,'on'); ylabel(ax1,'Instantaneous drift (\mus/day)');
legend(ax1,'Location','best');
ax2 = nexttile(layout); hold(ax2,'on');
plot(ax2,elapsedHours,elliptical.model.gravitational.accumulatedMicroseconds, ...
    'LineWidth',1.8,'Color',[0.12 0.55 0.28]);
plot(ax2,elapsedHours, ...
    elliptical.model.kinematic.accumulatedApproximateMicroseconds, ...
    'LineWidth',1.8,'Color',[0.78 0.20 0.18]);
plot(ax2,elapsedHours, ...
    elliptical.model.accumulatedNetApproximateMicroseconds, ...
    'LineWidth',2.2,'Color',[0.08 0.30 0.62]);
grid(ax2,'on'); xlabel(ax2,'Elapsed coordinate time (h)');
ylabel(ax2,'Accumulated difference (\mus)');
titleHandle = title(layout,'Elliptical-Orbit Relativistic Clock Behavior');
subtitleHandle = subtitle(layout, ...
    '500 km perigee x 20,200 km apogee over one orbital period');
titleHandle.Color = [0.12 0.12 0.12];
subtitleHandle.Color = [0.12 0.12 0.12];
applyReportTheme(figures(4));
end

function applyReportTheme(figureHandle)
axesHandles = findall(figureHandle,'Type','axes');
set(axesHandles,'Color','white','XColor',[0.12 0.12 0.12], ...
    'YColor',[0.12 0.12 0.12],'ZColor',[0.12 0.12 0.12], ...
    'GridColor',[0.72 0.72 0.72],'GridAlpha',0.5);
legendHandles = findall(figureHandle,'Type','legend');
set(legendHandles,'Color','white','TextColor',[0.12 0.12 0.12], ...
    'EdgeColor',[0.45 0.45 0.45]);
textHandles = findall(figureHandle,'Type','text');
set(textHandles,'Color',[0.12 0.12 0.12]);
end
